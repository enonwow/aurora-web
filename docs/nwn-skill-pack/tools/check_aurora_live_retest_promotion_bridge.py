#!/usr/bin/env python3
"""Check the Aurora live retest promotion bridge generator."""

from __future__ import annotations

import argparse
import importlib.util
import json
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from types import ModuleType


SCRATCH = Path(".codex-tmp/aurora-live-retest-promotion-bridge")
REAL_REPORT = Path("knowledge-inbox/aurora-live-retest-promotion-bridge.md")
SYNTHETIC_PASS_ID = "alrr-synthetic-promotion-bridge-pass"
SYNTHETIC_BLOCKED_ID = "alrr-synthetic-promotion-bridge-blocked"


@dataclass
class RetestPromotionBridgeCheck:
    checks: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    def ok(self, message: str) -> None:
        self.checks.append(message)

    def error(self, message: str) -> None:
        self.errors.append(message)


def load_module(path: Path, name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def run_command(command: list[str], cwd: Path) -> str:
    completed = subprocess.run(
        command,
        cwd=str(cwd),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    output = completed.stdout.strip()
    if completed.returncode != 0:
        raise RuntimeError("command failed: " + " ".join(command) + "\n" + output)
    return output


def require_text(result: RetestPromotionBridgeCheck, text: str, token: str, label: str) -> None:
    if token in text:
        result.ok(f"{label} includes {token}")
    else:
        result.error(f"{label} missing {token}")


