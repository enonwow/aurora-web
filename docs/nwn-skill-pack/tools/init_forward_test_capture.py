#!/usr/bin/env python3
"""Initialize a no-answer-leak forward-test answer capture sheet."""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


TEMPLATE = Path("forward-tests/answer-capture-template.md")
MATRIX = Path("forward-tests/reviewer-matrix.json")
DEFAULT_OUT_DIR = Path(".codex-tmp/forward-test-captures")


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def compact_timestamp(value: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "", value)[:32] or "capture"


def load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def load_tests(root: Path) -> dict[str, dict[str, Any]]:
    matrix = load_json(root / MATRIX)
    tests = matrix.get("tests", [])
    if not isinstance(tests, list):
        raise ValueError("reviewer matrix tests must be a list")
    result: dict[str, dict[str, Any]] = {}
    for item in tests:
        if isinstance(item, dict) and isinstance(item.get("test_id"), str):
            result[item["test_id"]] = item
    return result


def skill_path(root: Path) -> str:
    manifest = load_json(root / "version-manifest.json")
    authoring_skill = str(manifest.get("authoring_skill", "")).strip()
    return f"{root.as_posix()}/{authoring_skill}" if authoring_skill else root.as_posix()


def replace_line(line: str, prefix: str, value: str) -> str:
    if line.startswith(prefix):
        return f"{prefix} {value}"
    return line


def generate(root: Path, test_id: str, captured_at: str | None = None) -> str:
    tests = load_tests(root)
    test = tests.get(test_id)
    if not test:
        raise ValueError(f"unknown forward-test id: {test_id}")

    prompt_file = str(test.get("prompt_file", "")).strip()
    if not prompt_file:
        raise ValueError(f"{test_id} has no prompt_file in reviewer matrix")

    captured = captured_at or now_iso()
    title = str(test.get("title", "")).strip()
    template = (root / TEMPLATE).read_text(encoding="utf-8")

    lines: list[str] = []
    for line in template.splitlines():
        line = replace_line(line, "- Test id:", test_id)
        line = replace_line(line, "- Prompt file:", prompt_file)
        line = replace_line(line, "- Skill path:", skill_path(root))
        line = replace_line(line, "- Captured at:", captured)
        lines.append(line)

    lines.extend([
        "",
        "## Capture Sheet Metadata",
        "",
        f"- Generated for: {test_id} {title}",
        f"- Generated at: {captured}",
        "- Generated by: `tools/init_forward_test_capture.py`",
        "- No reviewer-only expected references or scoring fields are included in this sheet.",
    ])
    return "\n".join(lines) + "\n"


def output_path(root: Path, test_id: str, captured_at: str) -> Path:
    return root / DEFAULT_OUT_DIR / f"{test_id.lower()}-{compact_timestamp(captured_at)}.md"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default="docs/nwn-skill-pack")
    parser.add_argument("--test-id", required=True)
    parser.add_argument("--captured-at", default="")
    parser.add_argument("--out", default="")
    parser.add_argument("--stdout", action="store_true")
    args = parser.parse_args()

    root = Path(args.root)
    captured_at = args.captured_at or now_iso()
    try:
        output = generate(root, args.test_id, captured_at)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        print(output, end="")
        return 0

    out_path = Path(args.out) if args.out else output_path(root, args.test_id, captured_at)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(output, encoding="utf-8")
    print(out_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
