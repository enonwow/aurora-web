#!/usr/bin/env python3
"""Check Aurora live retest promotion decision helper."""

from __future__ import annotations

import argparse
import importlib.util
import json
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from types import ModuleType


SCRATCH = Path(".codex-tmp/aurora-live-retest-promotion-decision")
PASS_ID = "alrr-synthetic-promotion-decision-pass"
BLOCKED_ID = "alrr-synthetic-promotion-decision-blocked"


@dataclass
class PromotionDecisionCheck:
    checks: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    def ok(self, message: str) -> None:
        self.checks.append(message)

    def error(self, message: str) -> None:
        self.errors.append(message)


def load_module(path: Path, name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def load_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain an object")
    return data


def run_command(command: list[str], cwd: Path, expect_success: bool = True) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(
        command,
        cwd=str(cwd),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    if expect_success and completed.returncode != 0:
        raise RuntimeError("command failed: " + " ".join(command) + "\n" + completed.stdout.strip())
    if not expect_success and completed.returncode == 0:
        raise RuntimeError("command unexpectedly passed: " + " ".join(command) + "\n" + completed.stdout.strip())
    return completed


def create_retest_result(root: Path, records: Path, record_id: str, result_value: str) -> Path:
    atom = "toolset.buildAndClientRun"
    args = [
        sys.executable,
        str(root / "tools" / "aurora_live_retest_result_record.py"),
        "new",
        "--out",
        str(records),
        "--id",
        record_id,
        "--source-review-outcome-id",
        f"alro-{record_id}",
        "--source-review-outcome-path",
        f"knowledge-inbox/aurora-live-review-outcomes/records/alro-{record_id}.json",
        "--live-record-id",
        f"aurora-live-{record_id}",
        "--live-record-path",
        f"knowledge-inbox/aurora-live-records/aurora-live-{record_id}.json",
        "--evidence-manifest-path",
        f"knowledge-inbox/aurora-live-evidence-manifests/aurora-live-{record_id}.json",
        "--target-atom",
        atom,
        "--requested-next-action",
        "Maintainer promotion decision helper fixture.",
        "--operator",
        "synthetic-promotion-decision",
        "--toolset-version",
        "synthetic Toolset",
        "--nwn-ee-version",
        "synthetic NWN EE",
        "--environment-summary",
        "Synthetic promotion decision checker.",
        "--result",
        result_value,
        "--decision-summary",
        "Synthetic retest result for promotion decision helper.",
        "--check-run",
        "check_aurora_live_retest_result_records.py",
        "--check-passed",
        "check_aurora_live_retest_result_records.py",
        "--privacy-summary",
        "Synthetic checker record contains no private data.",
        "--dispatch-check",
        "--result-template-check",
        "--records-check",
        "--evidence-manifest-check",
        "--intake-consistency-check",
        "--redaction-policy-check",
        "--visual-redaction-check",
        "--verification-notes",
        "Synthetic promotion decision helper fixture.",
        "--non-proof-boundary",
        "Synthetic promotion decision fixture is not runtime proof and not automatic skill improvement.",
        "--notes",
        "Generated by check_aurora_live_retest_promotion_decision.py under .codex-tmp only.",
    ]
    if result_value == "pass":
        args.extend([
            "--passed-atom",
            atom,
            "--returned-artifact",
            ".codex-tmp/aurora-live-retest-promotion-decision/redacted-screenshot.png",
            "--artifact-hash",
            "redacted-screenshot.png=bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb",
            "--no-private-data",
        ])
    elif result_value == "blocked":
        args.extend([
            "--blocked-atom",
            atom,
            "--next-action",
            "Return exact blocker to maintainer.",
        ])
    output = run_command(args, cwd=root).stdout.strip()
    path = Path(output.splitlines()[-1])
    if not path.is_absolute():
        path = root / path
    return path


def run(root: Path) -> PromotionDecisionCheck:
    result = PromotionDecisionCheck()
    try:
        root = root.resolve()
        scratch = root / SCRATCH
        if scratch.exists():
            shutil.rmtree(scratch)
        source_records = scratch / "retest-results"
        decisions = scratch / "decisions"
        source_records.mkdir(parents=True, exist_ok=True)
        decisions.mkdir(parents=True, exist_ok=True)

        helper = root / "tools" / "aurora_live_retest_promotion_decision.py"
        reference_tool = load_module(root / "tools" / "reference_promotion_record.py", "reference_promotion_decision_check")

        pass_record = create_retest_result(root, source_records, PASS_ID, "pass")
        blocked_record = create_retest_result(root, source_records, BLOCKED_ID, "blocked")
        result.ok("created synthetic pass and blocked source retest results under .codex-tmp")

        held = run_command(
            [
                sys.executable,
                str(helper),
                str(root),
                "--source-retest-result",
                str(blocked_record),
                "--out",
                str(decisions),
                "--proposal-path",
                "knowledge-inbox/aurora-live-retest-promotion-bridge.md",
                "--result",
                "held",
                "--maintainer",
                "synthetic-maintainer",
                "--notes",
                "Synthetic held decision; no references patched.",
            ],
            cwd=root,
        )
        held_path = Path(held.stdout.strip().splitlines()[-1])
        held_record = load_json(held_path)
        held_errors = reference_tool.validate_record(held_record)
        if held_errors:
            result.error("held promotion decision should validate: " + "; ".join(held_errors))
        elif held_record.get("semver") == "NONE" and held_record.get("evidence_label") == "unverified":
            result.ok("held promotion decision validates with semver NONE and unverified label")
        else:
            result.error("held promotion decision has unexpected semver or evidence label")

        rejected = run_command(
            [
                sys.executable,
                str(helper),
                str(root),
                "--source-retest-result",
                str(pass_record),
                "--out",
                str(decisions),
                "--proposal-path",
                "knowledge-inbox/aurora-live-retest-promotion-bridge.md",
                "--result",
                "accepted",
                "--maintainer",
                "synthetic-maintainer",
                "--target-reference",
                "draft-skills/nwn-server-gamedev/references/aurora-live-toolset-buildandclientrun.md",
            ],
            cwd=root,
            expect_success=False,
        )
        if "--references-patched" in rejected.stdout:
            result.ok("accepted promotion decision without patch/release flags is rejected")
        else:
            result.error("accepted promotion decision failed for the wrong reason: " + rejected.stdout.strip())

        accepted = run_command(
            [
                sys.executable,
                str(helper),
                str(root),
                "--source-retest-result",
                str(pass_record),
                "--out",
                str(decisions),
                "--proposal-path",
                "knowledge-inbox/aurora-live-retest-promotion-bridge.md",
                "--result",
                "accepted",
                "--maintainer",
                "synthetic-maintainer",
                "--target-reference",
                "draft-skills/nwn-server-gamedev/references/aurora-live-toolset-buildandclientrun.md",
                "--references-patched",
                "--authoring-and-plugin-synced",
                "--privacy-checked",
                "--version-manifest-updated",
                "--plugin-manifest-updated",
                "--source-of-truth-updated",
                "--release-handoff-updated",
                "--promoted-record-path",
                "knowledge-inbox/promoted/alrr-synthetic-promotion-decision-pass.json",
                "--notes",
                "Synthetic accepted decision with explicit maintainer patch/release flags.",
            ],
            cwd=root,
        )
        accepted_path = Path(accepted.stdout.strip().splitlines()[-1])
        accepted_record = load_json(accepted_path)
        accepted_errors = reference_tool.validate_record(accepted_record)
        if accepted_errors:
            result.error("accepted promotion decision should validate: " + "; ".join(accepted_errors))
        elif (
            accepted_record.get("evidence_label") == "runtime-tested"
            and accepted_record.get("semver") == "MINOR"
            and len(accepted_record.get("target_references", [])) == 2
        ):
            result.ok("accepted promotion decision validates with runtime-tested evidence and paired reference targets")
        else:
            result.error("accepted promotion decision has unexpected evidence label, semver, or target references")

        validate = run_command(
            [
                sys.executable,
                str(root / "tools" / "reference_promotion_record.py"),
                "validate",
                str(decisions),
            ],
            cwd=root,
        )
        if "OK" in validate.stdout:
            result.ok("scratch promotion decisions validate through reference_promotion_record.py")
        else:
            result.error("scratch promotion decision CLI validate output did not include OK")
    except Exception as exc:
        result.error(str(exc))
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default="docs/nwn-skill-pack")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    result = run(Path(args.root))
    if args.json:
        print(json.dumps({"checks": result.checks, "errors": result.errors}, indent=2))
    else:
        for check in result.checks:
            print(f"OK: {check}")
        for error in result.errors:
            print(f"ERROR: {error}")
        if result.errors:
            print(f"Aurora live retest promotion decision check failed: {len(result.errors)} error(s)")
        else:
            print("Aurora live retest promotion decision check passed")
    return 1 if result.errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
