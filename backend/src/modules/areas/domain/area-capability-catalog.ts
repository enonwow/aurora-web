function buildSummary(items: readonly Readonly<AreaCapabilityItem>[]) {
  const implementation: Record<AreaCapabilityImplementationState, number> = {
    implemented: 0,
    partial: 0,
    preserve_only: 0,
    not_started: 0,
  };
  const release: Record<AreaCapabilityReleaseState, number> = {
    available: 0,
    blocked: 0,
    hidden: 0,
  };
  for (const item of items) {
    implementation[item.implementation] += 1;
    release[item.release] += 1;
  }
  return Object.freeze({
    total: items.length,
    implementation: Object.freeze(implementation),
    release: Object.freeze(release),
  });
}

function freezeCatalog(items: readonly Readonly<AreaCapabilityItem>[]): AreaCapabilityCatalog {
  const frozenItems = Object.freeze(items.map((item) => Object.freeze({
    ...item,
    testIds: Object.freeze([...item.testIds]),
    proofIds: Object.freeze([...item.proofIds]),
    blockers: Object.freeze([...item.blockers]),
  })));
  return Object.freeze({
    schemaVersion: AREA_CAPABILITY_SCHEMA_VERSION,
    catalogRevision: AREA_CAPABILITY_CATALOG_REVISION,
    items: frozenItems,
    summary: buildSummary(frozenItems),
  });
}

const catalog = freezeCatalog(sortedRows);

export function buildAreaCapabilityCatalog(): AreaCapabilityCatalog {
  return catalog;
}

export function validateAreaCapabilityCatalog(value: unknown): AreaCapabilityCatalog | null {
  const result = catalogSchema.safeParse(value);
  if (!result.success) return null;
  const items = result.data.items;
  const ids = items.map((item) => item.id);
  const orderedIds = [...ids].sort((left, right) => left.localeCompare(right));
  if (new Set(ids).size !== ids.length || ids.some((id, index) => id !== orderedIds[index])) {
    return null;
  }
  for (const item of items) {
    if (item.release === "available" &&
      (item.implementation !== "implemented" || item.auroraEvidence === "missing")) {
      return null;
    }
    if ((item.implementation === "preserve_only" || item.implementation === "not_started") &&
      item.release === "available") {
      return null;
    }
    if (item.auroraEvidence === "verified" && item.testIds.length + item.proofIds.length === 0) {
      return null;
    }
  }
  const normalized = freezeCatalog(items);
  if (JSON.stringify(normalized.summary) !== JSON.stringify(result.data.summary)) return null;
  return normalized;
}
