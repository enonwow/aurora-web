function capability(
  id: string,
  scope: AreaCapabilityScope,
  label: string,
  owner: AreaCapabilityOwner,
  auroraEvidence: AreaCapabilityEvidenceState,
  implementation: AreaCapabilityImplementationState,
  release: AreaCapabilityReleaseState,
  options: RowOptions = {},
): Readonly<AreaCapabilityItem> {
  const testIds = options.testIds ?? (auroraEvidence === "verified" ? [SCOPE_TEST[scope]] : []);
  return Object.freeze({
    id,
    scope,
    label,
    owner,
    auroraEvidence,
    implementation,
    release,
    testIds: Object.freeze([...testIds]),
    proofIds: Object.freeze([...(options.proofIds ?? [])]),
    blockers: Object.freeze([...(options.blockers ?? [])]),
  });
}

