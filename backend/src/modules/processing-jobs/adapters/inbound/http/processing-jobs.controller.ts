import { Body, Controller, Get, Headers, HttpCode, Param, Post, Query, Req } from "@nestjs/common";
import {
  ApiBearerAuth,
  ApiOperation,
  ApiParam,
  ApiResponse,
  ApiTags
} from "@nestjs/swagger";
import { AppConfigService } from "../../../../../common/config/app-config.service";
import { buildSuccessEnvelope } from "../../../../../common/http/contract";
import type { AppRequest } from "../../../../../common/http/request.types";
import { Permissions } from "../../../../auth/adapters/inbound/http/permissions.decorator";
import { Roles } from "../../../../auth/adapters/inbound/http/roles.decorator";
import { ProcessingJobsApplicationService } from "../../../application/processing-jobs.application.service";
import {
  parseCreateJobPayload,
  parseJobActionPayload,
  parseJobIdParams,
  parseJobListQuery,
  parseJobMetricsQuery,
  parseJobStatusBatchPayload
} from "./processing-jobs.schemas";

@Controller("processing/jobs")
@ApiTags("processing-jobs")
@ApiBearerAuth("bearer")
@Roles("builder", "dm", "admin")
export class ProcessingJobsController {
  constructor(
    private readonly service: ProcessingJobsApplicationService,
    private readonly config: AppConfigService
  ) {}

  @Post()
  @HttpCode(202)
  @Permissions("processing.placeable.run")
  @ApiOperation({
    summary:
      "Enqueue processing job for placeable/creature/item/area. Intended to evolve into Redis-backed async queue."
  })
  @ApiResponse({ status: 202, description: "Job was accepted and queued." })
  @ApiResponse({ status: 401, description: "Missing or invalid session." })
  @ApiResponse({ status: 403, description: "Forbidden for role/permission." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async createJob(
    @Req() request: AppRequest,
    @Headers("x-idempotency-key") rawIdempotencyKey: string | undefined,
    @Body() body: Record<string, unknown>
  ) {
    const parsed = parseCreateJobPayload(body);
    const command = {
      ...parsed,
      idempotencyKey: parsed.idempotencyKey ?? normalizeOptionalHeader(rawIdempotencyKey),
      traceId: parsed.traceId ?? request.requestId
    };
    const data = await this.service.enqueueJob(command, request.auth!.user.username);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get()
  @Permissions("processing.placeable.read")
  @ApiOperation({ summary: "List recent processing jobs." })
  @ApiResponse({ status: 200, description: "Jobs list payload." })
  @ApiResponse({ status: 401, description: "Missing or invalid session." })
  @ApiResponse({ status: 403, description: "Forbidden for role/permission." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async listJobs(
    @Req() request: AppRequest,
    @Query() query: Record<string, unknown>
  ) {
    const parsed = parseJobListQuery(query);
    const data = await this.service.listJobs(parsed.limit);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get("metrics")
  @Permissions("processing.placeable.read")
  @ApiOperation({
    summary:
      "Queue observability metrics for processing jobs (status counters and p50/p95 execution durations)."
  })
  @ApiResponse({ status: 200, description: "Processing queue metrics payload." })
  @ApiResponse({ status: 401, description: "Missing or invalid session." })
  @ApiResponse({ status: 403, description: "Forbidden for role/permission." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async getQueueMetrics(
    @Req() request: AppRequest,
    @Query() query: Record<string, unknown>
  ) {
    const parsed = parseJobMetricsQuery(query);
    const data = await this.service.getQueueMetrics(parsed.windowSize);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Post("status")
  @HttpCode(200)
  @Permissions("processing.placeable.read")
  @ApiOperation({
    summary: "Get status/details for a batch of processing jobs."
  })
  @ApiResponse({ status: 200, description: "Batch job status payload." })
  @ApiResponse({ status: 401, description: "Missing or invalid session." })
  @ApiResponse({ status: 403, description: "Forbidden for role/permission." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async getJobsStatus(
    @Req() request: AppRequest,
    @Body() body: Record<string, unknown>
  ) {
    const parsed = parseJobStatusBatchPayload(body);
    const data = await this.service.getJobsStatus(parsed.jobIds);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get(":jobId")
  @Permissions("processing.placeable.read")
  @ApiOperation({ summary: "Get processing job status/details." })
  @ApiParam({ name: "jobId", description: "UUID generated by enqueue endpoint." })
  @ApiResponse({ status: 200, description: "Single job payload." })
  @ApiResponse({ status: 404, description: "Job not found." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async getJob(
    @Req() request: AppRequest,
    @Param() params: Record<string, unknown>
  ) {
    const parsed = parseJobIdParams(params);
    const data = await this.service.getJob(parsed.jobId);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get(":jobId/result")
  @Permissions("processing.placeable.read")
  @ApiOperation({
    summary:
      "Get terminal job result payload. Returns conflict while job is still queued/running."
  })
  @ApiParam({ name: "jobId", description: "UUID generated by enqueue endpoint." })
  @ApiResponse({ status: 200, description: "Completed job result payload." })
  @ApiResponse({ status: 404, description: "Job not found." })
  @ApiResponse({
    status: 409,
    description: "Job is not in terminal success state yet (or failed)."
  })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async getJobResult(
    @Req() request: AppRequest,
    @Param() params: Record<string, unknown>
  ) {
    const parsed = parseJobIdParams(params);
    const data = await this.service.getJobResult(parsed.jobId);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Post(":jobId/retry")
  @HttpCode(202)
  @Permissions("processing.placeable.run")
  @ApiOperation({ summary: "Requeue failed/cancelled processing job." })
  @ApiParam({ name: "jobId", description: "UUID generated by enqueue endpoint." })
  @ApiResponse({ status: 202, description: "Job was requeued." })
  @ApiResponse({ status: 404, description: "Job not found." })
  @ApiResponse({ status: 409, description: "Job is not retryable." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async retryJob(
    @Req() request: AppRequest,
    @Param() params: Record<string, unknown>
  ) {
    const parsed = parseJobIdParams(params);
    const data = await this.service.retryJob(parsed.jobId, request.auth!.user.username);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Post(":jobId/cancel")
  @HttpCode(202)
  @Permissions("processing.placeable.run")
  @ApiOperation({ summary: "Cancel queued/running processing job." })
  @ApiParam({ name: "jobId", description: "UUID generated by enqueue endpoint." })
  @ApiResponse({ status: 202, description: "Job cancellation was accepted." })
  @ApiResponse({ status: 404, description: "Job not found." })
  @ApiResponse({ status: 409, description: "Job is not cancellable." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async cancelJob(
    @Req() request: AppRequest,
    @Param() params: Record<string, unknown>,
    @Body() body: Record<string, unknown>
  ) {
    const parsedParams = parseJobIdParams(params);
    const parsedBody = parseJobActionPayload(body);
    const data = await this.service.cancelJob(
      parsedParams.jobId,
      request.auth!.user.username,
      parsedBody.reason
    );
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }
}

function normalizeOptionalHeader(value: string | undefined): string | undefined {
  if (!value) {
    return undefined;
  }
  const normalized = value.trim();
  return normalized.length > 0 ? normalized : undefined;
}
