import { Body, Controller, Get, HttpCode, Param, Post, Query, Req } from "@nestjs/common";
import {
  ApiBearerAuth,
  ApiOperation,
  ApiParam,
  ApiResponse,
  ApiTags
} from "@nestjs/swagger";
import { AppConfigService } from "../../../../../common/config/app-config.service";
import { buildSuccessEnvelope } from "../../../../../common/http/contract";
import type { AppRequest } from "../../../../../common/http/request.types";
import { Permissions } from "../../../../auth/adapters/inbound/http/permissions.decorator";
import { Roles } from "../../../../auth/adapters/inbound/http/roles.decorator";
import { ProcessingJobsApplicationService } from "../../../application/processing-jobs.application.service";
import {
  parseCreateJobPayload,
  parseJobIdParams,
  parseJobListQuery
} from "./processing-jobs.schemas";

@Controller("processing/jobs")
@ApiTags("processing-jobs")
@ApiBearerAuth("bearer")
@Roles("builder", "dm", "admin")
export class ProcessingJobsController {
  constructor(
    private readonly service: ProcessingJobsApplicationService,
    private readonly config: AppConfigService
  ) {}

  @Post()
  @HttpCode(202)
  @Permissions("processing.placeable.run")
  @ApiOperation({
    summary:
      "Enqueue processing job for placeable/creature/item/area. Intended to evolve into Redis-backed async queue."
  })
  @ApiResponse({ status: 202, description: "Job was accepted and queued." })
  @ApiResponse({ status: 401, description: "Missing or invalid session." })
  @ApiResponse({ status: 403, description: "Forbidden for role/permission." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async createJob(
    @Req() request: AppRequest,
    @Body() body: Record<string, unknown>
  ) {
    const parsed = parseCreateJobPayload(body);
    const data = this.service.enqueueJob(parsed, request.auth!.user.username);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get()
  @Permissions("processing.placeable.read")
  @ApiOperation({ summary: "List recent processing jobs." })
  @ApiResponse({ status: 200, description: "Jobs list payload." })
  @ApiResponse({ status: 401, description: "Missing or invalid session." })
  @ApiResponse({ status: 403, description: "Forbidden for role/permission." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async listJobs(
    @Req() request: AppRequest,
    @Query() query: Record<string, unknown>
  ) {
    const parsed = parseJobListQuery(query);
    const data = this.service.listJobs(parsed.limit);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get(":jobId")
  @Permissions("processing.placeable.read")
  @ApiOperation({ summary: "Get processing job status/details." })
  @ApiParam({ name: "jobId", description: "UUID generated by enqueue endpoint." })
  @ApiResponse({ status: 200, description: "Single job payload." })
  @ApiResponse({ status: 404, description: "Job not found." })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async getJob(
    @Req() request: AppRequest,
    @Param() params: Record<string, unknown>
  ) {
    const parsed = parseJobIdParams(params);
    const data = this.service.getJob(parsed.jobId);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }

  @Get(":jobId/result")
  @Permissions("processing.placeable.read")
  @ApiOperation({
    summary:
      "Get terminal job result payload. Returns conflict while job is still queued/running."
  })
  @ApiParam({ name: "jobId", description: "UUID generated by enqueue endpoint." })
  @ApiResponse({ status: 200, description: "Completed job result payload." })
  @ApiResponse({ status: 404, description: "Job not found." })
  @ApiResponse({
    status: 409,
    description: "Job is not in terminal success state yet (or failed)."
  })
  @ApiResponse({ status: 422, description: "Validation failed." })
  async getJobResult(
    @Req() request: AppRequest,
    @Param() params: Record<string, unknown>
  ) {
    const parsed = parseJobIdParams(params);
    const data = this.service.getJobResult(parsed.jobId);
    return buildSuccessEnvelope(this.config.contractVersion, request, data);
  }
}
