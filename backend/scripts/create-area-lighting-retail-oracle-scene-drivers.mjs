function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function writeText(path, value) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, value, "utf8");
}

function readErfEntryIndex(sourcePath) {
  const bytes = readFileSync(sourcePath);
  if (bytes.length < 160) {
    throw new Error(`ERF file is too small: ${sourcePath}`);
  }
  const signature = bytes.toString("ascii", 0, 4);
  const version = bytes.toString("ascii", 4, 8);
  if (!["MOD ", "HAK ", "ERF ", "NWM "].includes(signature)) {
    throw new Error(`Unsupported ERF signature ${JSON.stringify(signature)} in ${sourcePath}`);
  }
  if (version !== "V1.0" && version !== "V1.1") {
    throw new Error(`Unsupported ERF version ${JSON.stringify(version)} in ${sourcePath}`);
  }

  const keyEntrySize = version === "V1.1" ? 40 : 24;
  const resrefLength = version === "V1.1" ? 32 : 16;
  const entryCount = bytes.readUInt32LE(16);
  const keyListOffset = bytes.readUInt32LE(24);
  const resourceListOffset = bytes.readUInt32LE(28);
  const keys = new Set();

  for (let index = 0; index < entryCount; index += 1) {
    const keyOffset = keyListOffset + index * keyEntrySize;
    const resourceOffset = resourceListOffset + index * 8;
    const resref = bytes
      .subarray(keyOffset, keyOffset + resrefLength)
      .toString("ascii")
      .replace(/\0.*$/u, "")
      .trim()
      .toLowerCase();
    const type = bytes.readUInt16LE(keyOffset + resrefLength + 4);
    const size = bytes.readUInt32LE(resourceOffset + 4);
    keys.add(`${resref}:${type}`);
    if (size < 0) {
      throw new Error(`Invalid resource size in ${sourcePath}`);
    }
  }

  return {
    path: sourcePath,
    fileName: sourcePath.split(/[\\/]/u).at(-1),
    entryCount,
    keys,
  };
}

function listModuleIndexes(modulesDir) {
  if (!modulesDir || !existsSync(modulesDir)) {
    return {
      modulesDir,
      status: "missing-modules-dir",
      modules: [],
      errors: [],
    };
  }

  const modules = [];
  const errors = [];
  for (const fileName of readdirSync(modulesDir)) {
    if (!fileName.toLowerCase().endsWith(".mod")) {
      continue;
    }
    const modulePath = join(modulesDir, fileName);
    try {
      modules.push(readErfEntryIndex(modulePath));
    } catch (error) {
      errors.push({
        modulePath,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  return {
    modulesDir,
    status: modules.length > 0 ? "modules-indexed" : "no-modules-found",
    modules,
    errors,
  };
}

function hasResource(moduleIndex, resref, type) {
  return moduleIndex.keys.has(`${resref.toLowerCase()}:${type}`);
}

function buildDriverStatus(driver, moduleIndex) {
  const compiledCandidates = [];
  const sourceCandidates = [];
  const missingCompiledDriverScripts = [];
  const missingSourceDriverScripts = [];

  for (const module of moduleIndex.modules) {
    if (hasResource(module, driver.scriptResref, RESOURCE_TYPES.ncs)) {
      compiledCandidates.push(module.path);
    }
    if (hasResource(module, driver.scriptResref, RESOURCE_TYPES.nss)) {
      sourceCandidates.push(module.path);
    }
  }

  if (compiledCandidates.length === 0) {
    missingCompiledDriverScripts.push(driver.scriptResref);
  }
  if (sourceCandidates.length === 0) {
    missingSourceDriverScripts.push(driver.scriptResref);
  }

  return {
    compiledDriverPresent: compiledCandidates.length > 0,
    sourceDriverPresentInModule: sourceCandidates.length > 0,
    compiledCandidates,
    sourceCandidates,
    missingCompiledDriverScripts,
    missingSourceDriverScripts,
  };
}

function buildManifest(repoRoot, outRoot, artifactDir, moduleIndex, generatedFiles) {
  const drivers = DRIVERS.map((driver) => {
    const sourcePath = join(outRoot, "generated-scripts", `${driver.scriptResref}.nss`);
    const status = buildDriverStatus(driver, moduleIndex);
    const sourceStats = statSync(sourcePath);
    return {
      caseId: driver.caseId,
      title: driver.title,
      scriptResref: driver.scriptResref,
      sourcePath: toRepoRelative(repoRoot, sourcePath),
      sourceSha256: sha256(readFileSync(sourcePath)),
      sourceBytes: sourceStats.size,
      sourceReady: true,
      requiredCompiledResource: `${driver.scriptResref}.ncs`,
      requiredAreaResrefs: driver.requiredAreaResrefs,
      requiredModuleResources: driver.requiredModuleResources,
      requiredRuntimeArtifacts: driver.requiredRuntimeArtifacts,
      requiredObservations: driver.requiredObservations,
      ...status,
      status: status.compiledDriverPresent
        ? "compiled-driver-present-runtime-capture-still-required"
        : "source-prepared-compiled-driver-missing",
      canonicalParityPromoted: false,
    };
  });

  const compiledReadyCount = drivers.filter((driver) => driver.compiledDriverPresent).length;
  const sourceReadyCount = drivers.filter((driver) => driver.sourceReady).length;

  return {
    version: "aurora-area-lighting-retail-oracle-scene-drivers/v1",
    generatedAt: new Date().toISOString(),
    status:
      compiledReadyCount === drivers.length
        ? "compiled-scene-drivers-present-runtime-capture-required"
        : "source-prepared-compiled-drivers-missing",
    repoRoot,
    outputRoot: toRepoRelative(repoRoot, outRoot),
    artifactDir: toRepoRelative(repoRoot, artifactDir),
    generatedFiles,
    safety: {
      launchesRetailProcess: false,
      compilesScripts: false,
      injectsModuleResources: false,
      doesNotFabricateRetailArtifacts: true,
      canonicalParityPromoted: false,
    },
    moduleScan: {
      modulesDir: moduleIndex.modulesDir,
      status: moduleIndex.status,
      moduleCount: moduleIndex.modules.length,
      errorCount: moduleIndex.errors.length,
      errors: moduleIndex.errors,
    },
    summary: {
      driverCount: drivers.length,
      sourceReadyCount,
      compiledReadyCount,
      missingCompiledDriverCount: drivers.length - compiledReadyCount,
      runtimeArtifactCount: drivers.reduce(
        (total, driver) => total + driver.requiredRuntimeArtifacts.length,
        0,
      ),
      optionalUtilityScriptCount: UTILITY_SCRIPTS.length,
      optionalCustomOracleScriptCount: UTILITY_SCRIPTS.filter((utility) =>
        utility.scriptResref.includes("zero"),
      ).length,
      canonicalParityPromoted: false,
    },
    drivers,
    nextRequiredActions: [
      "Compile generated-scripts/*.nss into .ncs with the retail NWScript compiler profile.",
      "Inject the six compiled .ncs resources into the disposable retail/toolset oracle module.",
      "For campfire and cross-lane cases, add or place the exact required blueprints/objects listed in requiredModuleResources.",
      "Run or attach NWN/toolset and capture the listed PNG/JSON artifacts from the staged scenes.",
      "Rerun create-area-lighting-blocked-compare-reports.mjs and check-area-lighting-retail-oracle-artifacts.mjs --allow-blocked.",
    ],
    nonEvidenceNotice:
      "Generated script sources are staging assets only. They are not retail/toolset capture proof and do not satisfy the missing oracle PNG/slot artifacts.",
  };
}

function renderMarkdown(manifest) {
  const lines = [
    "# Area Lighting Retail Oracle Scene Drivers",
    "",
    `Generated: ${manifest.generatedAt}`,
    `Status: \`${manifest.status}\``,
    "",
    "This pack prepares NWScript source drivers for the six required light/shadow retail oracle scenes, plus optional isolated lane-reference utility scripts. It does not compile, inject, launch NWN, capture screenshots, or promote parity.",
    "",
    "## Summary",
    "",
    `- Source-ready drivers: ${manifest.summary.sourceReadyCount}/${manifest.summary.driverCount}`,
    `- Compiled drivers present in scanned modules: ${manifest.summary.compiledReadyCount}/${manifest.summary.driverCount}`,
    `- Runtime artifacts still required: ${manifest.summary.runtimeArtifactCount}`,
    `- Optional utility scripts: ${manifest.utilityScripts?.length ?? 0}`,
    "",
    "## Drivers",
    "",
  ];

  for (const driver of manifest.drivers) {
    lines.push(
      `### ${driver.scriptResref} - ${driver.caseId}`,
      "",
      `- Status: \`${driver.status}\``,
      `- Source: \`${driver.sourcePath}\``,
      `- Required compiled resource: \`${driver.requiredCompiledResource}\``,
      `- Required runtime artifacts: ${driver.requiredRuntimeArtifacts.map((artifact) => `\`${artifact}\``).join(", ")}`,
      `- Compiled candidates: ${driver.compiledCandidates.length}`,
      "",
      "Required observations:",
      "",
      ...driver.requiredObservations.map((observation) => `- ${observation}`),
      "",
    );
  }

  if ((manifest.utilityScripts?.length ?? 0) > 0) {
    lines.push("## Utility Scripts", "");
    for (const utility of manifest.utilityScripts) {
      lines.push(
        `### ${utility.resref} - ${utility.title}`,
        "",
        `- Source: \`${utility.path}\``,
        `- Purpose: ${utility.purpose}`,
        "",
      );
    }
  }

  lines.push(
    "## Next Required Actions",
    "",
    ...manifest.nextRequiredActions.map((action) => `- ${action}`),
    "",
    "Do not treat this pack as retail proof. It is only scene-driver preparation.",
    "",
  );

  return `${lines.join("\n")}\n`;
}

try {
  const options = parseArgs(process.argv.slice(2));
  const repoRoot = resolve(options.repoRoot);
  const outRoot = toAbsolute(repoRoot, options.outRoot);
  const artifactDir = toAbsolute(repoRoot, options.artifactDir);
  const generatedScriptsDir = join(outRoot, "generated-scripts");
  mkdirSync(generatedScriptsDir, { recursive: true });

  const generatedFiles = [];
  const includePath = join(generatedScriptsDir, DRIVER_INCLUDE.fileName);
  writeText(includePath, DRIVER_INCLUDE.source);
  generatedFiles.push({
    path: toRepoRelative(repoRoot, includePath),
    kind: "include-source",
    resref: DRIVER_INCLUDE.resref,
    sha256: sha256(DRIVER_INCLUDE.source),
  });

  for (const driver of DRIVERS) {
    const sourcePath = join(generatedScriptsDir, `${driver.scriptResref}.nss`);
    writeText(sourcePath, driver.source);
    generatedFiles.push({
      path: toRepoRelative(repoRoot, sourcePath),
      kind: "driver-source",
      caseId: driver.caseId,
      resref: driver.scriptResref,
      sha256: sha256(driver.source),
    });
  }

  const utilityScripts = [];
  for (const utility of UTILITY_SCRIPTS) {
    const sourcePath = join(generatedScriptsDir, `${utility.scriptResref}.nss`);
    writeText(sourcePath, utility.source);
    const entry = {
      path: toRepoRelative(repoRoot, sourcePath),
      kind: "utility-source",
      title: utility.title,
      purpose: utility.purpose,
      resref: utility.scriptResref,
      sha256: sha256(utility.source),
    };
    generatedFiles.push(entry);
    utilityScripts.push(entry);
  }

  const moduleIndex = listModuleIndexes(options.nwnModulesDir);
  const manifest = buildManifest(repoRoot, outRoot, artifactDir, moduleIndex, generatedFiles);
  manifest.utilityScripts = utilityScripts;
  const manifestPath = join(outRoot, "retail-oracle-scene-drivers-manifest.json");
  const markdownPath = join(outRoot, "retail-oracle-scene-drivers.md");
  writeText(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  writeText(markdownPath, renderMarkdown(manifest));

  console.log(
    JSON.stringify(
      {
        status: manifest.status,
        manifest: toRepoRelative(repoRoot, manifestPath),
        markdown: toRepoRelative(repoRoot, markdownPath),
        summary: manifest.summary,
      },
      null,
      2,
    ),
  );
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
