#!/usr/bin/env node
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const atom = resolve("backend/scripts/observe-aurora-toolset-pending-hak-rebuild-no-global-input.mjs");
const source = readFileSync(atom, "utf8");
assert.match(source, /TdlgVerifyModule/);
assert.match(source, /Build Module/);
assert.match(source, /TfrmIFOProp/);
assert.match(source, /EnumChildWindows/);
assert.match(source, /IsWindowEnabled/);
assert.match(source, /\["No errors found"\]/);
assert.match(source, /text-eq'Done'-and\$_\.enabled/);
assert.match(source, /text-eq'Build'-and-not\$_\.enabled/);
assert.match(source, /status='settled'/);
assert.match(source, /else\{'building'\}/);
assert.doesNotMatch(source, /if\(\$build\.Count-eq1\)\{\$status='building'\}/);
assert.match(source, /else\{'building'\}/);
assert.match(source, /status='settled'/);
assert.match(source, /postsNoMessages=\$true/);
assert.match(source, /doesNotVerifyHakPersistence=\$true/);
assert.doesNotMatch(source, /PostMessage|SendMessage|SendInput|SetCursorPos|Start-Sleep/);
const parseScript = "$path=$env:ATOM;$text=Get-Content -Raw $path;$marker='const source = String.raw'+[char]96;$start=$text.IndexOf($marker);if($start-lt0){throw 'source_marker_missing'};$start+=$marker.Length;$end=$text.IndexOf(([char]96+';'),$start);if($end-lt0){throw 'source_terminator_missing'};[void][ScriptBlock]::Create($text.Substring($start,$end-$start));'powershell_source_parse_ok'";
const output = execFileSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command", parseScript], { encoding: "utf8", env: { ...process.env, ATOM: atom } });
assert.match(output, /powershell_source_parse_ok/);
